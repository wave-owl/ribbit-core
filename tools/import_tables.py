#!/usr/bin/env python3
"""Regenerate src/ribbit_tables.c from the reference's polar_tables.hh and base37_bitmap.hh.

Usage: python3 tools/import_tables.py ref/rattlegram/app/src/main/cpp src/ribbit_tables.c
"""
import sys
from pathlib import Path

HEADER = """/* Tables copied verbatim from Rattlegram (0BSD), regenerated by tools/import_tables.py:
 * polar_tables.hh (frozen bit sets of the (2048, 1392), (2048, 1056) and (2048, 712) polar
 * codes) and base37_bitmap.hh (8x11 raster font of the 37 base-37 characters, fancy header).
 */
#include "ribbit_internal.h"

"""


def main(src: str, dst: str) -> int:
    cpp = Path(src)
    polar = (cpp / "polar_tables.hh").read_text().replace(
        "static const uint32_t frozen_", "const uint32_t rb_frozen_")
    bitmap = (cpp / "base37_bitmap.hh").read_text().replace(
        "static const uint8_t base37_bitmap", "const uint8_t rb_base37_bitmap")
    keep = [ln for ln in (polar + "\n" + bitmap).splitlines()
            if ln.startswith("const ") or not ln.strip()]
    Path(dst).write_text(HEADER + "\n".join(ln for ln in keep if ln.strip()) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(*sys.argv[1:3]))
